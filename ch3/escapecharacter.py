# 1. \n [Newline]
print("1. Hello\nworld")

#2. \t [Horizontal line]
print("2. Hello\tworld")

#3. \'[single quote]
print('3. It\'s birthday today')

#  or 
print("3. It's birthday today")

#4. \" [double quote]
print("4. \"Hi,\" everyone")

#or
print('4. "hi," everyone')

#5. \\ [backslash]
print("5. The path is for C.\\users")

#6.\r [ carriage return]
print(' What is your roll no. is 6 \r6. Nav  ')             # /r=override /r6. =6. in begining & after "Nav" if don't space then output= Navis..... , If"Nav  " = space also override then output= Nav your roll.... 

#7.\b [backspace]
print("7. Hello \bguys")            # \t and \b same but distance b/w 2 words is different